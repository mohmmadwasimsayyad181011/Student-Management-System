"""List methods for subjects and marks."""
subjects = ["Python", "DBMS", "Maths"]
subjects.append("Networks")
print("append:", subjects)
subjects.insert(0, "English")
print("insert:", subjects)
subjects.extend(["Physics", "Chemistry"])
print("extend:", subjects)
print("count Python:", subjects.count("Python"))
print("index DBMS:", subjects.index("DBMS"))
subjects.remove("English")
print("remove:", subjects)
removed = subjects.pop()
print("pop removed:", removed, "remaining:", subjects)
subjects.sort()
print("sort:", subjects)
subjects.reverse()
print("reverse:", subjects)
copy_for_clear = subjects.copy()
copy_for_clear.clear()
print("clear:", copy_for_clear)
